import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {modelFor} from './prepare.mjs';
import {migrationManifest} from '../../validation/prepare-lot2b.mjs';
const root=fileURLToPath(new URL('../../../',import.meta.url));
const output=fs.realpathSync(process.argv[2]);
if(path.dirname(output)!==path.join(root,'target'))throw Error('Unexpected campaign location');
const manifest=JSON.parse(fs.readFileSync(path.join(output,'manifest.json')));
const model=JSON.parse(fs.readFileSync(path.join(output,'compose.json')));
assert.deepEqual(model,modelFor(root,manifest.run,manifest.group));
assert.equal(path.basename(output),model.name);
assert.equal(manifest.project,model.name);
assert.equal(manifest.commit,execFileSync('git',['rev-parse','HEAD'],{cwd:root,encoding:'utf8'}).trim());
const limit=Object.values(model.services).reduce((n,s)=>n+parseInt(s.mem_limit),0);
assert.equal(manifest.hostFreeRequiredMiB,limit+1536);
assert.equal(manifest.dockerRequiredMiB,limit+512);
assert.deepEqual(manifest.migrations,migrationManifest(root));
assert.deepEqual(manifest.jars.map(j=>j.service).sort(),Object.keys(model.services).filter(n=>n.endsWith('-service')).sort(),'Missing service artifact record');
const sha=p=>crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
assert.equal(Object.keys(manifest.configFiles??{}).length,4,'Configuration fingerprints missing');
for(const[p,h]of Object.entries(manifest.configFiles))assert.equal(sha(path.join(output,p)),h,'Configuration drift');
for(const[p,h]of Object.entries(manifest.sourceFiles))assert.equal(sha(path.join(root,p)),h,'Source drift: '+p);
for(const row of manifest.jars){assert.ok(row.sha256,'Missing JAR');assert.equal(sha(row.path),row.sha256,'JAR drift');}
const bundle=path.join(output,'frontend-dist/browser');
assert.ok(manifest.frontendFiles && Object.keys(manifest.frontendFiles).length,'Frontend not sealed');
for(const[p,h]of Object.entries(manifest.frontendFiles))assert.equal(sha(path.join(output,p)),h,'Frontend drift');
assert.ok(fs.existsSync(path.join(bundle,'index.html')),'Production frontend build missing');
for(const name of fs.readdirSync(bundle).filter(n=>n.endsWith('.js')))assert.ok(!fs.readFileSync(path.join(bundle,name),'utf8').includes('http://localhost:8080'),'Development origin in bundle');
assert.equal(fs.readFileSync(path.join(output,'gateway/application-validation.yml'),'utf8'),fs.readFileSync(path.join(root,'microservices/gateway-service/src/main/resources/application.yml'),'utf8').replaceAll('http://localhost:4200','http://localhost:14200'));
console.log('PASS: model, source/JAR/migration fingerprints and production frontend origin; runtime not validated.');
